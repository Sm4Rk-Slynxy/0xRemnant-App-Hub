/* Browser workflow QA against browser_server.py's modeled Docker runtime. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require(process.env.APPHUB_PLAYWRIGHT || 'playwright');

(async () => {
  const browser = await chromium.launch({headless:true,args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(process.env.APPHUB_TEST_BASE || 'http://127.0.0.1:18764');
  await page.locator('#auth:not([hidden])').waitFor();
  await page.locator('#setup-token').fill(fs.readFileSync(path.join(process.env.APPHUB_TEST_DATA, '.setup-token'),'utf8').trim());
  await page.locator('#password').fill('browser-test-password-123');
  await page.locator('#auth-submit').click();
  await page.locator('#shell:not([hidden])').waitFor();
  await page.locator('#empty:not([hidden])').waitFor();
  assert.equal(await page.locator('#stat-total').textContent(), '0');
  const buffer = fs.readFileSync(process.env.APPHUB_BROWSER_ZIP || path.join(__dirname,'../examples/hello-app.zip'));
  await page.locator('#upload-button').click();
  await page.locator('#zip-file').setInputFiles({name:'little-notes.zip',mimeType:'application/zip',buffer});
  await page.locator('#app-name').fill('Little Notes <test>');
  await page.locator('#advanced summary').click();
  await page.locator('#environment').fill('DEMO_KEY=browser-secret-value');
  await page.locator('#deploy-submit').click();
  await page.locator('#log-dialog[open]').waitFor();
  await page.waitForFunction(() => document.getElementById('log-status').textContent === 'Ready');
  await page.locator('#log-dialog [data-close]').first().click();
  assert.equal(await page.locator('.app-card h3').textContent(), 'Little Notes <test>');
  assert.equal(await page.locator('.app-card h3 test').count(), 0);
  assert.equal(await page.locator('#stat-running').textContent(), '1');
  let frameContent = '<!doctype html><title>App test frame</title><h1>Frame ready</h1>';
  await page.route('http://127.0.0.1:10000/**', route => route.fulfill({status:200,contentType:'text/html',body:frameContent}));
  await page.locator('.card-open').click();
  await page.locator('.app-pane:not([hidden])').waitFor();
  assert.equal(await page.locator('.app-frame').getAttribute('src'),'http://127.0.0.1:10000/');
  await page.locator('[data-tab="home"]').click();
  assert.equal(await page.locator('.app-frame').count(),1);
  await page.locator('[data-actions]').selectOption('update');
  const html = '<!doctype html><title>HTML app</title><button id=increment>Add one</button><span id=count>0</span><script>let n=0;document.getElementById("increment").onclick=()=>document.getElementById("count").textContent=++n;</script>';
  frameContent = html;
  await page.locator('#zip-file').setInputFiles({name:'little-notes-v2.HTML',mimeType:'text/html',buffer:Buffer.from(html)});
  assert.equal(await page.locator('#app-type').inputValue(),'static');
  assert.equal(await page.locator('#internal-port').inputValue(),'8080');
  await page.locator('#deploy-submit').click();
  await page.waitForFunction(() => document.getElementById('log-status').textContent === 'Ready');
  await page.locator('#log-dialog [data-close]').first().click();
  await page.locator('.card-open').click();
  await page.frameLocator('.app-frame').locator('#increment').click();
  assert.equal(await page.frameLocator('.app-frame').locator('#count').textContent(),'1');
  await page.locator('[data-tab="home"]').click();
  await page.locator('[data-actions]').selectOption('versions');
  await page.locator('#versions-dialog[open]').waitFor();
  assert.equal(await page.locator('.version-row').count(),2);
  await page.locator('[data-restore]').click();
  await page.waitForFunction(() => document.getElementById('log-status').textContent === 'Ready');
  await page.locator('#log-dialog [data-close]').first().click();
  await page.locator('#search').fill('no-such-app');
  await page.locator('#no-results:not([hidden])').waitFor();
  await page.locator('#search').fill('');
  await page.locator('[data-actions]').selectOption('stop');
  await page.waitForFunction(() => document.getElementById('stat-running').textContent === '0');
  await page.locator('[data-actions]').selectOption('start');
  await page.waitForFunction(() => document.getElementById('stat-running').textContent === '1');
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.locator('#upload-button').click();
  assert.ok(await page.locator('#upload-dialog').evaluate(element => element.getBoundingClientRect().width < innerWidth));
  await page.locator('#upload-dialog [data-close]').first().click();
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#upload-button').click();
  const dropped = await page.evaluateHandle(content => {const data=new DataTransfer();data.items.add(new File([content],'standalone-tool.htm',{type:'text/html'}));return data;},html);
  await page.locator('#dropzone').dispatchEvent('drop',{dataTransfer:dropped});
  assert.equal(await page.locator('#app-name').inputValue(),'standalone tool');
  assert.equal(await page.locator('#app-type').inputValue(),'static');
  await page.locator('#deploy-submit').click();
  await page.waitForFunction(() => document.getElementById('log-status').textContent === 'Ready');
  await page.locator('#log-dialog [data-close]').first().click();
  assert.equal(await page.locator('.app-card').count(),2);
  await page.locator('#signout').click();
  await page.locator('#auth:not([hidden])').waitFor();
  assert.equal(await page.evaluate(() => sessionStorage.getItem('apphub-token')),null);
  assert.deepEqual(errors,[]);
  console.log('PASS: setup, ZIP upload, HTML update, interactive HTML frame, HTM drag-and-drop, safe names, tabs, version restore, search, stop/start, mobile layout, logout; no browser JavaScript errors. Docker modeled.');
  await browser.close();
})().catch(error => {console.error(error);process.exit(1);});
